#!/usr/bin/env python3
"""Supplementary material for the Apidologie submission."""
import csv, os
from collections import Counter
from docx import Document
from docx.shared import Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH

REPO = "/home/claude/honeybee-wing-reliability-"
RES = os.path.join(REPO, "results")
doc = Document()
st = doc.styles["Normal"]
st.font.name = "Times New Roman"; st.font.size = Pt(11)
st.paragraph_format.line_spacing = 1.0
st.paragraph_format.space_after = Pt(6)
for s in doc.sections:
    s.top_margin = s.bottom_margin = s.left_margin = s.right_margin = Cm(2.5)

B = {"b": True}; I = {"i": True}; N = {}
def para(t="", align=None, bold=False):
    p = doc.add_paragraph(); r = p.add_run(t); r.bold = bold
    if align is not None: p.alignment = align
    return p
def rich(parts):
    p = doc.add_paragraph()
    for t, f in parts:
        r = p.add_run(t); r.bold = f.get("b", False); r.italic = f.get("i", False)
    return p
def h(lvl, t):
    p = doc.add_paragraph(); r = p.add_run(t); r.bold = True
    r.font.size = Pt(13 if lvl == 1 else 11)
    return p
def tbl(hdr, rows):
    t = doc.add_table(rows=1, cols=len(hdr)); t.style = "Table Grid"
    for i, c in enumerate(hdr):
        cell = t.rows[0].cells[i]; cell.text = ""
        r = cell.paragraphs[0].add_run(c); r.bold = True
        r.font.size = Pt(9)
    for row in rows:
        cs = t.add_row().cells
        for i, v in enumerate(row):
            cs[i].text = ""
            r = cs[i].paragraphs[0].add_run(str(v)); r.font.size = Pt(9)
    doc.add_paragraph()

para("Supplementary material", align=WD_ALIGN_PARAGRAPH.CENTER, bold=True)
para()
para("Disagreement between independently produced honey bee wing datasets "
     "is localized at two landmarks and limits reference transfer",
     align=WD_ALIGN_PARAGRAPH.CENTER)
para("V. K. Chaudhari and J. J. Pastagia", align=WD_ALIGN_PARAGRAPH.CENTER)
para()
para("All tables below are generated by the analysis scripts at "
     "https://github.com/vkcvaibhav-eng/honeybee-wing-reliability- and are "
     "reproduced by running the numbered scripts in sequence. Procrustes "
     "units throughout.")
doc.add_page_break()

# ---------------------------------------------------------------- Table S1
h(1, "Table S1")
para("Root-mean-square disagreement between the two measurement sets at each "
     "of the 19 landmarks, in units of centroid size, on all 642 "
     "algorithmically matched candidate pairs and on the 608 retained after "
     "removing the 34 largest discrepancies. Landmarks 7 and 14 are the two "
     "whose position Nawrocka et al. (2018) report changing relative to "
     "Gerula et al. (2009). The final column gives the residual between the "
     "two generalized Procrustes mean shapes, recovered independently at the "
     "landmark-matching step.")
lm = {int(r["landmark_nawrocka_scheme"]): r
      for r in csv.DictReader(open(os.path.join(
          RES, "per_landmark_both_samples.csv")))}
mapres = {int(r["deposit_b_landmark"]): float(r["mean_shape_residual"])
          for r in csv.DictReader(open(os.path.join(RES, "landmark_map.csv")))}
rows = []
for k in range(1, 20):
    rows.append([k, lm[k]["rms_all_642"], lm[k]["rms_retained_608"],
                 f"{mapres[k]:.5f}",
                 "convention change" if k in (7, 14) else ""])
tbl(["Landmark", "RMS, all 642", "RMS, retained 608", "Mean-shape residual",
     "Note"], rows)

# ---------------------------------------------------------------- Table S2
h(1, "Table S2")
para("Procrustes distance between the grand means of every pair of the nine "
     "analytical datasets, with the digitizing group and region of each. "
     "These are differences between datasets, in which population, provenance "
     "and measurement are confounded; only the Ecuadorian pair isolates "
     "measurement.")
off = list(csv.DictReader(open(os.path.join(RES, "offset_matrix.csv"))))
off.sort(key=lambda r: float(r["offset"]))
tbl(["Dataset A", "Dataset B", "Distance", "Comparison",
     "Group A", "Group B"],
    [[r["deposit_a"], r["deposit_b"], f"{float(r['offset']):.5f}",
      r["comparison"], r["group_a"], r["group_b"]] for r in off])

# ---------------------------------------------------------------- Table S3
h(1, "Table S3")
para("Assignment of all 24 genotypes of the instrumentally inseminated cross "
     "dataset, before and after grand-mean centring, at 12 principal "
     "components. Counts are colonies. The two conflicting colony "
     "identifiers are excluded before the centring offset is fitted, leaving "
     "198 colony groups and 9,464 wings.")
kr = list(csv.DictReader(open(os.path.join(RES,
                                           "known_crosses_assignments.csv"))))
CLS = ["carnica", "caucasia", "mellifera"]
order = (["P0cc", "P1cc", "P0kk", "P1kk", "P0mm", "P1mm",
          "F1ck", "F1kc", "F1cm", "F1mc", "F1km", "F1mk"]
         + sorted({r["genotype"] for r in kr if r["genotype"].startswith("BC")}))
rows = []
for g in order:
    sub = [r for r in kr if r["genotype"] == g]
    if not sub:
        continue
    cr = Counter(r["assigned_raw"] for r in sub)
    cc = Counter(r["assigned_corrected"] for r in sub)
    rows.append([g, len(sub), sum(int(r["wings"]) for r in sub)]
                + [cr.get(c, 0) for c in CLS] + [cc.get(c, 0) for c in CLS])
tbl(["Genotype", "Colonies", "Wings",
     "carnica (raw)", "caucasica (raw)", "mellifera (raw)",
     "carnica (centred)", "caucasica (centred)", "mellifera (centred)"], rows)

# ---------------------------------------------------------------- Table S4
h(1, "Table S4")
para("Exploratory conversion of every dataset pair to apparent African "
     "ancestry. The alignment column is the absolute cosine between the "
     "dataset difference and the ancestry direction fitted to 268 sequenced "
     "bees. The scale returns 31% for a pair whose measured ancestry "
     "difference is 20.4 percentage points, so these values are reported as "
     "exploratory and support no inference about ancestry. The 36 "
     "comparisons are not independent: each dataset enters eight of them.")
anc = list(csv.DictReader(open(os.path.join(RES, "ancestry_equivalents.csv"))))
anc.sort(key=lambda r: -float(r["abs_cosine"]))
tbl(["Dataset A", "Dataset B", "Distance", "Alignment", "Projected",
     "Apparent ancestry difference"],
    [[r["deposit_a"], r["deposit_b"], f"{float(r['offset']):.5f}",
      f"{float(r['abs_cosine']):.3f}", f"{float(r['projected']):.5f}",
      f"{100 * float(r['equivalent_delta_A']):.0f}%"] for r in anc])

# ---------------------------------------------------------------- Table S5
h(1, "Table S5")
para("Byte-identical duplicate records in the coordinate file of the first "
     "Ecuadorian deposit. Each duplicate lies within the same image and "
     "apiary as its original, so no record is shared between apiaries. "
     "Removing all ten leaves 632 matched candidate pairs and reduces the "
     "number above three times the median from 34 to 28; the mean "
     "displacement is unchanged at 0.00875. The analysis in the manuscript "
     "uses the deposit as published so that it reproduces from the "
     "deposited file without alteration.")
rows = []
for line in open(os.path.join(RES, "duplicate_records.md")):
    if line.startswith("| ") and "duplicate of" not in line and "---" not in line:
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) == 4 and c[0].isdigit():
            rows.append(c)
tbl(["Record duplicated", "Duplicate record", "Apiary", "Image"], rows)

h(1, "Table S6")
para("Effect of the duplicate records on every reported estimate.")
tbl(["Quantity", "As published (663 records)", "Duplicates removed (653)"], [
    ["Matched candidate pairs", "642", "632"],
    ["Median Procrustes distance", "0.00964", "0.00960"],
    ["Pairs above three times the median", "34", "28"],
    ["Mean displacement", "0.00875", "0.00875"],
    ["Half mean squared disagreement, all pairs", "0.000110", "0.000105"],
    ["Half mean squared disagreement, retained", "0.000052", "0.000050"],
])

# ---------------------------------------------------------------- note
h(1, "Reproduction")
para("Scripts run in numerical order from the scripts directory; paths are "
     "derived from the script location. Step 11 writes the figures and must "
     "run last. Dependencies are NumPy, SciPy, pandas, openpyxl, Pillow and "
     "Matplotlib. Raw datasets are not redistributed: every source is listed "
     "with its DOI in Table X of the manuscript.")

out = "/home/claude/Chaudhari_Pastagia_Apidologie_supplementary.docx"
doc.save(out)
print("wrote", out)
